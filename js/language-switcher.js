/* ============================================================
   Yusei Stay — Language switcher (shared disclosure component)
   Progressive enhancement over YuseiI18n: this module only builds
   and controls the open/close UI. All language state (current
   language, storage, ?lang= query param, DOM translation) stays in
   YuseiI18n — this module calls YuseiI18n.setLang() on selection and
   listens for "yusei:langchange" to keep every instance in sync.

   Markup contract — drop this anywhere a language switcher should
   appear (header, mobile menu, footer), on any page that also loads
   js/i18n.js first:

     <div class="lang-switcher" data-lang-switcher>
       <button type="button" class="lang-switcher__trigger" data-lang-trigger
               aria-expanded="false"
               data-i18n-attr="aria-label:nav.language.label">
         <svg class="lang-switcher__globe" ...></svg>
         <span data-i18n="nav.language.generic">言語</span>
       </button>
     </div>

   The option list (flag + native name per supported language) is
   generated by this script from a single data source below — never
   hand-write the <ul> of options in HTML, so flag artwork and the
   language list only ever live in one place.

   Interaction (see README "Language switcher" section for the full
   contract): pointer hover opens/keeps-open/closes with a short
   delay on desktop. Because click() fires mouseenter before click on
   mouse-capable browsers, the first click right after a hover-open
   only pins the list open (it does not toggle it closed) — a second
   deliberate click, keyboard Enter/Space, or a touch tap toggles as
   expected. Escape closes and restores focus to the trigger; outside
   click closes; the current language is marked with aria-current + a
   checkmark. This is a simple disclosure widget (button + list of
   buttons) — not a role="menu" or role="listbox" widget, so no
   arrow-key roving focus.
   ============================================================ */

